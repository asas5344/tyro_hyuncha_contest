#!/usr/bin/env python3
"""One shared cockpit, mounted at each vehicle's eye-forward / eye-height datum.
Local X forward, Y relative to eye height; driver's seat is at Z=-0.37 m.
The exterior GLBs are not regenerated by this tool.
"""
import math
from pathlib import Path
from glb_geometry import Glb

g=Glb()
g.materials[4]['pbrMetallicRoughness'].update(baseColorFactor=[.035,.042,.050,1],roughnessFactor=.85)
g.materials[5]['pbrMetallicRoughness'].update(baseColorFactor=[.30,.27,.23,1],roughnessFactor=.65)
g.materials.append({'name':'ambient_strip','pbrMetallicRoughness':{'baseColorFactor':[.12,.40,.43,1],'roughnessFactor':.5},'emissiveFactor':[.035,.16,.18],'doubleSided':True})

# A curved, closed dashboard shell: shallow on top, rounded toward the occupants.
cross=[(.56,-.38),(.54,-.27),(.59,-.19),(.72,-.145),(.91,-.155),(1.06,-.21),(1.06,-.38)]
rings=[]
for i in range(33):
 z=-.85+1.70*i/32
 sweep=.09*(abs(z)/.85)**2
 rings.append([(x-sweep,y-.025*(abs(z)/.85)**2,z) for x,y in cross])
faces=[[a[j],b[j],b[(j+1)%len(cross)],a[(j+1)%len(cross)]] for a,b in zip(rings,rings[1:]) for j in range(len(cross))]
g.mesh('dashboard',faces+[rings[0][::-1],rings[-1]],4,smooth=True)
for z in [-.70,-.08,.38,.70]:
 g.rounded_box('vent_housing',.557,-.245,z,.025,.050,.19,.009,2)
 for k in [-1,0,1]:g.box('vent_blade',.541,-.245+k*.012,z,.009,.003,.165,3)
for side in [-1,1]:
 g.rounded_box('door_card',.15,-.37,side*.825,1.6,.49,.07,.025,4)
 g.rounded_box('door_inlay',.18,-.33,side*.783,1.20,.15,.025,.010,5)
 g.rounded_box('door_armrest',.02,-.47,side*.745,.75,.07,.15,.025,4)
 g.rounded_box('door_handle',.48,-.29,side*.761,.16,.026,.018,.007,3)
 g.beam('door_ambient',(-.37,-.25,side*.779),(.70,-.25,side*.779),.003,14)
# Retain the existing runtime display planes and camera monitor coordinates.
g.rounded_box('instrument_cluster',.650,-.135,-.37,.070,.12,.38,.014,2)
g.box('instrument_display',.605,-.135,-.37,.006,.06,.27,8)
g.rounded_box('center_display',.625,-.125,.18,.064,.17,.29,.012,2)
g.box('center_screen',.600,-.125,.18,.006,.13,.25,8)
g.rounded_box('center_console',.08,-.56,.17,.94,.22,.29,.025,4)
g.rounded_box('center_armrest',-.20,-.425,.17,.33,.07,.27,.025,5)
for xx in [.24,.40]:
 g.surface('cupholder',lambda u,v,xx=xx:(xx+.055*math.cos(u*math.tau)*v,-.441,.17+.055*math.sin(u*math.tau)*v),24,4,2)
g.box('cabin_floor',.10,-.83,0,1.8,.03,1.65,4)
g.box('footwell_front',1.00,-.61,0,.04,.45,1.65,4)
g.rounded_box('knee_bolster',.73,-.49,0,.19,.28,1.62,.025,4)
g.rounded_box('room_mirror_housing',.80,.17,-.10,.028,.09,.28,.012,4)
g.beam('room_mirror_stem',(.80,.28,-.10),(.80,.21,-.10),.009,4)

# Hub and rim share one animation pivot; preserve the app's steering node name.
wheel=len(g.nodes);g.nodes.append({'name':'steering_wheel','translation':[.46,-.34,-.37],'children':[]})
faces=[]
for i in range(64):
 for j in range(12):
  face=[]
  for a,b in [(i,j),(i+1,j),(i+1,j+1),(i,j+1)]:
   t=a*math.tau/64;u=b*math.tau/12;rad=.18+.021*math.cos(u)
   face.append((.021*math.sin(u),max(-.165,rad*math.cos(t)),rad*math.sin(t)))
  faces.append(face)
g.mesh('steering_rim',faces,4,parent=wheel,smooth=True)
g.mesh('steering_column',[[(z+.15,y,x) for x,y,z in face] for face in g.cylinder(.045,.24,24)],4,parent=wheel,smooth=True)
g.box('steering_hub',-.004,0,0,.055,.080,.12,4,parent=wheel)
for side in [-1,1]:
 g.mesh('steering_spoke',[[(-.015,.025,side*.045),(-.015,.018,side*.169),(-.015,-.018,side*.169),(-.015,-.025,side*.045)]],3,parent=wheel)
 g.box('steering_buttons',-.026,0,side*.10,.012,.025,.045,2,parent=wheel)
g.mesh('steering_lower_spoke',[[(-.015,-.02,-.035),(-.015,-.16,-.027),(-.015,-.16,.027),(-.015,-.02,.035)]],3,parent=wheel)
out=Path(__file__).resolve().parents[1]/'app/src/main/assets/models/cockpit.glb'
g.save(out,{'origin':'driver eye forward and height; Z=vehicle centerline','driverRightM':-.37,'steeringForwardM':.46,'steeringHeightM':-.34,'sharedAcrossVehicles':True})
